/** Whether a value is a known ISO 3166-1 alpha-2 code. */
export function isCountryCode(code: string): boolean {
  return (COUNTRY_CODES as readonly string[]).includes(code)
}

const labelCache = new Map<string, Intl.DisplayNames>()

/** The country label for `code` in the given language (e.g. `EG` → "Egypt" / "مصر"),
 *  from the platform's Intl data; falls back to the raw code if it cannot be resolved. */
export function countryLabel(code: string, lang: string): string {
  try {
    let names = labelCache.get(lang)
    if (!names) {
      names = new Intl.DisplayNames([lang], { type: 'region' })
      labelCache.set(lang, names)
    }
    return names.of(code) ?? code
  } catch {
    return code
  }
}

/** A country option for the nationality Autocomplete. */
export interface CountryOption {
  code: string
  label: string
}

/** The full country list as `{ code, label }`, localized and sorted by label. */
export function countryOptions(lang: string): CountryOption[] {
  return COUNTRY_CODES.map((code) => ({ code, label: countryLabel(code, lang) })).sort((a, b) =>
    a.label.localeCompare(b.label, lang),
  )
}
